import express from 'express';
import path from 'path';
import { fileURLToPath } from 'url';
import { createServer as createViteServer } from 'vite';
import { GoogleGenAI } from '@google/genai';
import dotenv from 'dotenv';
import { backendRouter } from './backend/api.js';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Initialize Gemini Client
const ai = new GoogleGenAI({
  apiKey: process.env.GEMINI_API_KEY,
  httpOptions: {
    headers: {
      'User-Agent': 'aistudio-build',
    },
  },
});

async function startServer() {
  const app = express();
  const PORT = 3000;

  app.use(express.json());

  // Mount backend router for CSV logs, Scapy status, and XGBoost endpoints
  app.use('/api', backendRouter);

  // Health check endpoint
  app.get('/api/health', (req, res) => {
    res.json({
      status: 'ok',
      service: 'Self-Healing NIDS Engine',
      geminiConfigured: !!process.env.GEMINI_API_KEY,
      timestamp: new Date().toISOString(),
    });
  });

  // Gemini Threat Analysis & Playbook Generator API
  app.post('/api/gemini/analyze-threat', async (req, res) => {
    try {
      const {
        attackerIp,
        targetNodeName,
        targetNodeIp,
        attackType,
        anomalyScore,
        payloadEntropy,
        packetRate,
        recentLogs,
      } = req.body;

      if (!process.env.GEMINI_API_KEY) {
        return res.status(503).json({
          error: 'Gemini API key is not configured in environment variables.',
        });
      }

      const prompt = `
You are an expert Security Operations Center (SOC) Lead & Machine Learning NIDS Analyst.
Analyze the following live network intrusion event detected by our ML Anomaly Detection Engine:

- Attacker IP: ${attackerIp || '185.220.101.5'}
- Target Node Name: ${targetNodeName || 'Web Server Alpha'} (${targetNodeIp || '10.0.1.10'})
- Attack Classification: ${attackType || 'DDOS / SYN Flood'}
- ML Anomaly Score: ${anomalyScore || 0.94} / 1.00
- Payload Entropy: ${payloadEntropy || 7.82} (Normal baseline: < 4.2)
- Burst Packet Rate: ${packetRate || 42000} packets/sec
- Telemetry Context Logs:
${JSON.stringify(recentLogs || [], null, 2)}

Provide a structured, precise incident analysis in JSON format with the following schema:
{
  "threatLevel": "CRITICAL" | "HIGH" | "MEDIUM" | "LOW",
  "attackVector": "Short description of the technical exploit or flood vector",
  "cveEquivalent": "Relevant CVE or ATT&CK Technique ID (e.g. CVE-2023-34362 or T1498.001)",
  "rootCause": "Deep technical analysis of why this attack breached the normal baseline",
  "blastRadius": "Impact on subnets, adjacent databases, or downstream services",
  "recommendedPlaybook": [
    "Step 1: Quarantining target interface",
    "Step 2: Injecting BGP/IPTables block for attacker IP",
    "Step 3: Flushing malicious connection sockets",
    "Step 4: Executing automated snapshot rollback"
  ],
  "suggestedFirewallRule": "iptables -A INPUT -s [Attacker IP] -j DROP --comment 'NIDS ML Auto-Block'"
}
Return valid JSON only, no markdown markdown wraps if possible or raw JSON.
`;

      const response = await ai.models.generateContent({
        model: 'gemini-3.6-flash',
        contents: prompt,
        config: {
          responseMimeType: 'application/json',
          temperature: 0.2,
        },
      });

      const responseText = response.text || '{}';
      try {
        const parsedData = JSON.parse(responseText);
        res.json({ success: true, analysis: parsedData });
      } catch (parseErr) {
        res.json({
          success: true,
          analysis: {
            threatLevel: 'HIGH',
            attackVector: `${attackType} vector detected from ${attackerIp}`,
            rootCause: responseText,
            blastRadius: `Target node ${targetNodeName} isolated`,
            recommendedPlaybook: [
              'Auto-quarantine node',
              'Block source IP address',
              'Update perimeter firewall',
            ],
            suggestedFirewallRule: `iptables -A INPUT -s ${attackerIp} -j DROP`,
          },
        });
      }
    } catch (err: any) {
      console.error('Error calling Gemini API:', err);
      res.status(500).json({
        error: 'Failed to generate threat intelligence from Gemini AI',
        details: err?.message || String(err),
      });
    }
  });

  // Gemini Firewall Policy Explainer
  app.post('/api/gemini/explain-rule', async (req, res) => {
    try {
      const { rule } = req.body;
      if (!process.env.GEMINI_API_KEY) {
        return res.status(503).json({
          error: 'Gemini API key missing',
        });
      }

      const prompt = `Explain in concise 2-3 bullet points why the following firewall rule was auto-generated by the self-healing system and what risk it mitigates:
Rule details: ${JSON.stringify(rule)}`;

      const response = await ai.models.generateContent({
        model: 'gemini-3.6-flash',
        contents: prompt,
      });

      res.json({ success: true, explanation: response.text });
    } catch (err: any) {
      res.status(500).json({ error: err?.message || 'Error explaining rule' });
    }
  });

  // Vite middleware setup
  if (process.env.NODE_ENV !== 'production') {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), 'dist');
    app.use(express.static(distPath));
    app.get('*', (req, res) => {
      res.sendFile(path.join(distPath, 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`🛡️ Self-Healing NIDS Server listening on http://0.0.0.0:${PORT}`);
  });
}

startServer();
